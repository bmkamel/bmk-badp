import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {inspectBlueprint} from './blueprint-inspect.mjs';

const repo = 'bmkamel/bmk-badp';
const blueprintPath = 'docs/MASTER_BLUEPRINT.md';
const inspectorPath = 'scripts/blueprint-inspect.mjs';
const inventoryPaths = ['src/local-sqlite.mjs', 'src/development-runner.mjs',
  'scripts/source-live-pilot.mjs', 'scripts/publish-source-pilot.mjs', '.github/workflows/source-live-pilot.yml'];
const section = '## Cloud self-development evidence';
const git = (...args) => execFileSync('git', args, {encoding: 'utf8'}).trim();
const read = path => readFileSync(path, 'utf8');

function replaceOnce(source, old, next) {
  assert.equal(source.split(old).length, 2, 'unexpected source contract');
  return source.replace(old, () => next);
}

function plan(base) {
  const document = read(blueprintPath);
  const report = inspectBlueprint(document, Object.fromEntries(inventoryPaths.map(path => [path, read(path)])), base);
  const source = read(inspectorPath);
  if (!source.includes('const repositoryRoot =')) {
    return {id: 'inspector-portability', path: inspectorPath, report, content: improveInspector(source)};
  }
  const inputs = [...report.inventory, {path: inspectorPath, sha256: createHash('sha256').update(source).digest('hex')}];
  const body = [section, '', 'Generated by the BADP cloud workflow from the checked-out repository.',
    '', 'The blueprint inspector is verified from outside the repository working directory before publication.',
    '', '| Inspected file | SHA-256 |', '| --- | --- |',
    ...inputs.map(entry => '| `'+entry.path+'` | `'+entry.sha256+'` |'), ''].join('\n');
  const prefix = document.split('\n'+section+'\n');
  assert.ok(prefix.length <= 2);
  const content = prefix[0].trimEnd()+'\n\n'+body;
  if (content === document) return null;
  return {id: 'blueprint-evidence', path: blueprintPath, report, content};
}

function improveInspector(source) {
  let next = replaceOnce(source, "import {execFileSync} from 'node:child_process';",
    "import {execFileSync} from 'node:child_process';\nimport {fileURLToPath, pathToFileURL} from 'node:url';");
  next = replaceOnce(next, 'if(process.argv[1]&&new URL(import.meta.url).pathname===process.argv[1]){',
    "if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href){\n const repositoryRoot = fileURLToPath(new URL('../', import.meta.url));");
  next = replaceOnce(next, "{encoding:'utf8'}).trim();", "{encoding:'utf8',cwd:repositoryRoot}).trim();");
  return replaceOnce(next,
    "readFileSync('docs/MASTER_BLUEPRINT.md','utf8'),Object.fromEntries(paths.map(p=>[p,readFileSync(p,'utf8')]))",
    "readFileSync(new URL('../docs/MASTER_BLUEPRINT.md',import.meta.url),'utf8'),Object.fromEntries(paths.map(p=>[p,readFileSync(new URL('../'+p,import.meta.url),'utf8')]))");
}

function verify(task, base) {
  assert.equal(git('diff', '--name-only'), task.path);
  assert.equal(git('status', '--porcelain'), 'M '+task.path);
  assert.equal(read(task.path), task.content);
  git('diff', '--check');
  const run = JSON.parse(execFileSync(process.execPath, [fileURLToPath(new URL('./blueprint-inspect.mjs', import.meta.url))],
    {cwd: new URL('../.github/', import.meta.url), encoding: 'utf8'}));
  assert.equal(run.base, base);
  assert.equal(run.taskId, task.report.taskId);
  assert.equal(run.inventory.length, task.report.inventory.length);
  if (task.id === 'blueprint-evidence') assert.equal(plan(base), null);
}

async function publish(task, base) {
  const token = process.env.GH_TOKEN;
  const runId = process.env.GITHUB_RUN_ID;
  assert.ok(token && /^\d+$/.test(runId ?? ''));
  async function api(endpoint, method = 'GET', body) {
    const response = await fetch('https://api.github.com/repos/'+repo+endpoint, {
      method, redirect: 'error', signal: AbortSignal.timeout(15000),
      headers: {Authorization: 'Bearer '+token, Accept: 'application/vnd.github+json', 'Content-Type': 'application/json'},
      body: body === undefined ? undefined : JSON.stringify(body),
    });
    if (!response.ok) throw Error('github_'+method+'_'+response.status);
    if (response.status !== 204) return response.json();
  }
  assert.equal((await api('/git/ref/heads/main')).object.sha, base, 'stale main');
  const current = await api('/git/commits/'+base);
  const tree = await api('/git/trees', 'POST', {base_tree: current.tree.sha,
    tree: [{path: task.path, mode: '100644', type: 'blob', content: task.content}]});
  const commit = await api('/git/commits', 'POST', {tree: tree.sha, parents: [base],
    message: 'BADP: '+task.id+'\n\nVerified by https://github.com/'+repo+'/actions/runs/'+runId});
  await api('/git/refs/heads/main', 'PATCH', {sha: commit.sha, force: false});
  console.log('Published '+task.id+' at '+commit.sha);
  if (task.id === 'inspector-portability') {
    await api('/actions/workflows/self-development.yml/dispatches', 'POST', {ref: 'main'});
    console.log('Dispatched next blueprint task');
  }
}

const mode = process.argv[2];
const base = git('rev-parse', 'HEAD');
const output = process.env.RUNNER_TEMP+'/badp-self-task.json';
if (mode === 'prepare') {
  assert.equal(git('status', '--porcelain'), '');
  const task = plan(base);
  if (task) {
    writeFileSync(task.path, task.content);
    verify(task, base);
    writeFileSync(output, JSON.stringify({id: task.id, path: task.path, base, content: task.content}));
    console.log('Selected, planned and verified '+task.id);
  } else {
    console.log('No eligible task. Blueprint inventory is current.');
  }
} else if (mode === 'publish') {
  assert.equal(process.env.GITHUB_REPOSITORY, repo);
  assert.equal(process.env.GITHUB_REF, 'refs/heads/main');
  const candidate = JSON.parse(read(output));
  assert.equal(candidate.base, base);
  assert.ok([blueprintPath, inspectorPath].includes(candidate.path));
  const original = execFileSync('git', ['show', base+':'+candidate.path], {encoding: 'utf8'});
  assert.equal(read(candidate.path), candidate.content);
  writeFileSync(candidate.path, original);
  const task = plan(base);
  assert.deepEqual([task?.id, task?.path, task?.content], [candidate.id, candidate.path, candidate.content]);
  writeFileSync(task.path, task.content);
  verify(task, base);
  await publish(task, base);
} else {
  throw Error('invalid_mode');
}
